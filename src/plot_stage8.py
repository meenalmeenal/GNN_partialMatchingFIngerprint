"""Aggregate Stage 8 (FVC held-out fingers 51-100) results and draw the figures/tables."""
import json
import os

import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt
import numpy as np

D = "results/stage8/heldout"
DBS = ["fvc2002_db1", "fvc2002_db2", "fvc2002_db3", "fvc2004_db1", "fvc2004_db2", "fvc2004_db3",
       "fvc2002_db4", "fvc2004_db4"]
REAL = DBS[:6]            # real sensors; the last two are synthetic (SFinGe)
AREAS = ["100", "75", "50", "25", "10"]
METHODS = [  # key, label, colour, marker
    ("classical", "Classical Hough (no training)", "#2f7d5d", "o"),
    ("inv_local_fvcft", "Invariant GNN + MaxSim, fine-tuned on real FVC", "#00798c", "h"),
    ("inv_local", "Invariant GNN + MaxSim, SOCOFing only (zero-shot)", "#6a994e", "D"),
    ("inv_local_noise", "... + synthetic impression noise (zero-shot)", "#c0562b", "x"),
    ("v1_global", "Stage 3-style pooled GCN, stronger loss (zero-shot)", "#7a4aa8", "v"),
    ("stage3", "Stage 3 GCN (zero-shot)", "#8a8f99", "s"),
]
data = {db: json.load(open(f"{D}/{db}.json")) for db in DBS if os.path.exists(f"{D}/{db}.json")}


def avg(dbs, area, key, metric):
    v = [data[db]["levels"][area][key][metric] for db in dbs if db in data]
    return float(np.mean(v)) * (100 if metric in ("rank1", "rank5", "eer_z", "eer") else 1)


def table(dbs, title):
    lines = [f"**{title}**", "", "| method | " + " | ".join(f"{a} %" for a in AREAS) + " |",
             "|---|" + "---|" * len(AREAS)]
    for key, label, _, _ in METHODS:
        lines.append(f"| {label} | " + " | ".join(f"{avg(dbs, a, key, 'rank1'):.1f}" for a in AREAS) + " |")
    return "\n".join(lines)


def table_eer(dbs, title):
    lines = [f"**{title}**", "", "| method | " + " | ".join(f"{a} %" for a in AREAS) + " |",
             "|---|" + "---|" * len(AREAS)]
    for key, label, _, _ in METHODS:
        lines.append(f"| {label} | " + " | ".join(f"{avg(dbs, a, key, 'eer_z'):.1f}" for a in AREAS) + " |")
    return "\n".join(lines)


def per_db(area):
    keys = [m[0] for m in METHODS]
    lines = ["| database | " + " | ".join(k for k in keys) + " |", "|---|" + "---|" * len(keys)]
    for db in DBS:
        if db in data:
            e = data[db]["levels"][area]
            lines.append(f"| {db} | " + " | ".join(f"{e[k]['rank1'] * 100:.1f}" for k in keys) + " |")
    return "\n".join(lines)


out = ["# auto-generated by src/plot_stage8.py\n",
       table(REAL, "Rank-1 identification (%), mean over the 6 real-sensor databases (50 held-out fingers each, chance 2 %)"),
       "", table_eer(REAL, "Verification EER (%), impostor-cohort normalised, same databases"), "",
       table(DBS, "Rank-1 (%), mean over all 8 databases incl. the 2 synthetic ones"), "",
       "**Rank-1 (%) per database, full-print queries (100 %)**", "", per_db("100"), "",
       "**Rank-1 (%) per database, 25 % of the query print**", "", per_db("25")]
open("results/stage8/summary_tables.md", "w", encoding="utf-8").write("\n".join(out))

fig, ax = plt.subplots(1, 2, figsize=(11.8, 4.5))
x = [int(a) for a in AREAS]
for key, label, col, mk in METHODS:
    ax[0].plot(x, [avg(REAL, a, key, "rank1") for a in AREAS], marker=mk, color=col, lw=2.2 if key in
               ("classical", "inv_local_fvcft") else 1.4, label=label)
    ax[1].plot(x, [avg(REAL, a, key, "eer_z") for a in AREAS], marker=mk, color=col, lw=2.2 if key in
               ("classical", "inv_local_fvcft") else 1.4)
for a in ax:
    a.invert_xaxis(); a.grid(alpha=.3); a.set_xlabel("Query print area retained (%)")
ax[0].set_ylabel("Rank-1 identification (%)"); ax[0].set_title("Real FVC prints, held-out fingers (chance 2 %)")
ax[1].set_ylabel("EER (%), lower is better"); ax[1].set_title("Verification (impostor-cohort normalised)")
fig.legend(loc="lower center", ncol=2, frameon=False, fontsize=8.5)
fig.tight_layout(rect=(0, 0.2, 1, 1))
fig.savefig("results/stage8/headline.png", dpi=130)
print(open("results/stage8/summary_tables.md", encoding="utf-8").read())

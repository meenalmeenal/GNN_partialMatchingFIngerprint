"""Aggregate the Stage 10 training-seed replication (scripts/seed_replication.sh).

Independent runs: the original Stage 9d model (seed 42) and seeds 1 and 2. Determinism check: seed 42 trained
again with the identical command. Writes results/stage10/seed_summary.md and results/stage10/seeds.png."""
import csv
import json
import os

import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt
import numpy as np

REAL = [f"fvc{y}_db{d}" for y in (2002, 2004) for d in (1, 2, 3)]
R = "results/stage10"


def fvc(folder, key, area, metric="rank1"):
    return 100 * np.mean([json.load(open(f"{folder}/{db}.json"))["levels"][area][key][metric] for db in REAL])


def soco(path, area):
    return 100 * json.load(open(path))["modes"]["centred"][area]["learned"]["rank1"]


def best_val(log):
    rows = list(csv.DictReader(open(log)))
    return min(float(r["val_loss"]) for r in rows), len(rows)


RUNS = {  # name -> (fvc folder, zs key, ft folder, ft key, sweep json, training log)
    "seed 42 (original)": ("results/stage9d/fvc_newmodel", "inv_local_leader", "results/stage9d/fvc_ft",
                           "inv_local_leader_fvcft", "results/stage9d/sweep_centred_leader.json",
                           "results/stage9d_leader_inv_local/train_log.csv"),
}
for s in (1, 2, 42):
    d = f"{R}/seed{s}"
    RUNS[f"seed {s}" + (" (rerun)" if s == 42 else "")] = (d, "zs", d, "ft", f"{d}/socofing_centred.json",
                                                         f"results/stage10_seed{s}/train_log.csv")

METRICS = [  # label, function(run) -> value
    ("FVC zero-shot Rank-1 100 %", lambda r: fvc(r[0], r[1], "100")),
    ("FVC zero-shot Rank-1 50 %", lambda r: fvc(r[0], r[1], "50")),
    ("FVC zero-shot Rank-1 10 %", lambda r: fvc(r[0], r[1], "10")),
    ("FVC fine-tuned Rank-1 100 %", lambda r: fvc(r[2], r[3], "100")),
    ("FVC fine-tuned Rank-1 50 %", lambda r: fvc(r[2], r[3], "50")),
    ("FVC fine-tuned Rank-1 10 %", lambda r: fvc(r[2], r[3], "10")),
    ("FVC fine-tuned EER 100 %", lambda r: fvc(r[2], r[3], "100", "eer_z")),
    ("SOCOFing Rank-1 100 %", lambda r: soco(r[4], "100")),
    ("SOCOFing Rank-1 50 %", lambda r: soco(r[4], "50")),
    ("SOCOFing Rank-1 25 %", lambda r: soco(r[4], "25")),
    ("SOCOFing Rank-1 10 %", lambda r: soco(r[4], "10")),
]

vals, missing = {}, []
for name, r in RUNS.items():
    for label, fn in METRICS:
        try:
            vals[(name, label)] = fn(r)
        except Exception:
            missing.append((name, label))
    try:
        vals[(name, "best val loss")], vals[(name, "epochs run")] = best_val(r[5])
    except Exception:
        pass

names = list(RUNS)
indep = [n for n in names if n != "seed 42 (rerun)"]
labels = [m[0] for m in METRICS]
out = ["# auto-generated by src/aggregate_seeds.py\n",
       "**Training-seed replication of the final pipeline (LEADER graphs). Held-out FVC fingers = mean of the 6 real-sensor databases; "
       "SOCOFing = 897-finger gallery, minutia-centred windows (probe seed 0). mean +- sd over the three independent runs "
       "(seed 42 original, 1, 2); the last two columns repeat seed 42 with the identical command**", "",
       "| metric | " + " | ".join(indep) + " | mean +- sd | seed 42 (rerun) | rerun - original |",
       "|---|" + "---|" * (len(indep) + 3)]
for label in labels + ["best val loss", "epochs run"]:
    row = [vals.get((n, label)) for n in indep]
    f = "{:.4f}" if label == "best val loss" else ("{:.0f}" if label == "epochs run" else "{:.1f}")
    if any(v is None for v in row):
        out.append(f"| {label} | " + " | ".join("-" if v is None else f.format(v) for v in row) + " | - | - | - |")
        continue
    rr = vals.get(("seed 42 (rerun)", label))
    out.append(f"| {label} | " + " | ".join(f.format(v) for v in row) +
               f" | {np.mean(row):.2f} +- {np.std(row, ddof=1):.2f} | " +
               ("-" if rr is None else f.format(rr)) + " | " + ("-" if rr is None else f"{rr - row[0]:+.2f}") + " |")
if missing:
    out += ["", f"_missing (not yet produced): {sorted(set(n for n, _ in missing))}_"]
os.makedirs(R, exist_ok=True)
open(f"{R}/seed_summary.md", "w", encoding="utf-8").write("\n".join(out))
print("\n".join(out))

fig, ax = plt.subplots(figsize=(8.5, 4))
for i, label in enumerate(labels):
    xs = [vals[(n, label)] for n in indep if (n, label) in vals]
    ax.scatter([i] * len(xs), xs, color="#00798c", s=26, zorder=3)
    if len(xs) > 1:
        ax.errorbar([i], [np.mean(xs)], yerr=[np.std(xs, ddof=1)], color="#003f5c", capsize=4, lw=2, zorder=2)
ax.set_xticks(range(len(labels)))
ax.set_xticklabels(labels, rotation=60, ha="right", fontsize=7.5)
ax.set_ylabel("%"); ax.grid(alpha=.3)
ax.set_title("Training-seed spread (dots = runs, bar = mean +- sd)")
fig.tight_layout(); fig.savefig(f"{R}/seeds.png", dpi=120)

"""Tables and figure for Stage 9c (900-finger sweep, open-set, tuned classical on FVC)."""
import json
import os

import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt
import numpy as np

R = "results/stage9c"
AREAS = ["100", "75", "50", "25", "10"]
cen = json.load(open(f"{R}/sweep_centred.json"))["modes"]["centred"]
ran = json.load(open(f"{R}/sweep_random.json"))["modes"]["random"]
ran["100"] = cen["100"]
MODES = {"minutia-centred windows": cen, "uniform-random windows (Stage 7 demo)": ran}

out = ["# auto-generated by src/plot_stage9c.py\n"]
# ---------------------------------------------------------------- closed set
out += ["**Closed-set Rank-1 (%), 900-print gallery, 900 queries (one random altered probe per finger); "
        "95 % bootstrap CI over queries in brackets; learned also as mean ± sd over 3 probe/crop seeds**", "",
        "| windows | method | " + " | ".join(f"{a} %" for a in AREAS) + " |", "|---|---|" + "---|" * len(AREAS)]
for mname, m in MODES.items():
    for meth in ("learned", "classical"):
        cells = []
        for a in AREAS:
            e = m[a][meth]
            lo, hi = e["rank1_ci"]
            c = f"{e['rank1'] * 100:.1f} [{lo * 100:.0f}-{hi * 100:.0f}]"
            if meth == "learned":
                c += f" ({e['rank1_mean_over_seeds'] * 100:.1f}±{e['rank1_sd_over_seeds'] * 100:.1f})"
            cells.append(c)
        out.append(f"| {mname} | {meth} | " + " | ".join(cells) + " |")
# ---------------------------------------------------------------- open set
for z, zl in (("z", "z-scored top score (over the enrolled gallery)"), ("raw", "raw top score")):
    out += ["", f"**Open-set (half the fingers enrolled, half unknown), minutia-centred windows, decision on {zl}; "
            "DIR = enrolled queries correctly identified at rank 1 AND accepted, at the threshold giving the stated "
            "false-accept rate on unknown queries; mean of 2 random enrolment splits**", "",
            "| method | metric | " + " | ".join(f"{a} %" for a in AREAS) + " |", "|---|---|" + "---|" * len(AREAS)]
    for meth in ("learned", "classical"):
        for key, lab in (("DIR@FAR=1%", "DIR @ FAR 1 %"), ("DIR@FAR=10%", "DIR @ FAR 10 %"),
                         ("auc_known_vs_unknown", "AUC known vs unknown")):
            sc = 100 if "DIR" in key else 1
            out.append(f"| {meth} | {lab} | " + " | ".join(
                f"{cen[a]['open_set'][meth][z][key] * sc:.{1 if sc == 100 else 3}f}" for a in AREAS) + " |")

# ---------------------------------------------------------------- FVC tuned classical
H, T = "results/stage8/heldout", f"{R}/fvc_tuned"
DBS = [f"fvc{y}_db{d}" for y in (2002, 2004) for d in (1, 2, 3)]
if all(os.path.exists(f"{T}/{db}.json") for db in DBS):
    A = ["100", "75", "50", "25", "10"]

    def mean(src, key, area, metric="rank1"):
        return 100 * np.mean([json.load(open(f"{src}/{db}.json"))["levels"][area][key][metric] for db in DBS])

    out += ["", "**FVC held-out fingers 51-100, mean over the 6 real-sensor databases, Rank-1 % "
            "(Hough tolerances tuned on FVC set B only)**", "",
            "| method | " + " | ".join(f"{a} %" for a in A) + " |", "|---|" + "---|" * len(A)]
    for lab, src, key in (("classical, default tolerances (SOCOFing-tuned)", H, "classical"),
                          ("classical, tuned on FVC set B", T, "classical_tuned"),
                          ("learned, fine-tuned on FVC", H, "inv_local_fvcft"),
                          ("learned, SOCOFing only", H, "inv_local")):
        out.append(f"| {lab} | " + " | ".join(f"{mean(src, key, a):.1f}" for a in A) + " |")
    out += ["", "**Same, verification EER % (impostor-cohort normalised)**", "",
            "| method | " + " | ".join(f"{a} %" for a in A) + " |", "|---|" + "---|" * len(A)]
    for lab, src, key in (("classical, default", H, "classical"), ("classical, tuned on set B", T, "classical_tuned"),
                          ("learned, fine-tuned on FVC", H, "inv_local_fvcft")):
        out.append(f"| {lab} | " + " | ".join(f"{mean(src, key, a, 'eer_z'):.1f}" for a in A) + " |")
open(f"{R}/summary_tables.md", "w", encoding="utf-8").write("\n".join(out))
print("\n".join(out))

# ---------------------------------------------------------------- figure
fig, ax = plt.subplots(1, 2, figsize=(11.5, 4.4))
x = [int(a) for a in AREAS]
sty = {"learned": ("#00798c", "o"), "classical": ("#2f7d5d", "s")}
for (mname, m), ls in zip(MODES.items(), ("-", "--")):
    for meth, (col, mk) in sty.items():
        y = np.array([m[a][meth]["rank1"] for a in AREAS]) * 100
        lo = np.array([m[a][meth]["rank1_ci"][0] for a in AREAS]) * 100
        hi = np.array([m[a][meth]["rank1_ci"][1] for a in AREAS]) * 100
        ax[0].plot(x, y, ls, color=col, marker=mk, lw=2, label=f"{meth}, {mname}")
        ax[0].fill_between(x, lo, hi, color=col, alpha=0.10)
for meth, (col, mk) in sty.items():
    ax[1].plot(x, [cen[a]["open_set"][meth]["z"]["DIR@FAR=10%"] * 100 for a in AREAS], "-", color=col,
               marker=mk, lw=2, label=f"{meth} DIR @ FAR 10 %")
    ax[1].plot(x, [cen[a]["open_set"][meth]["z"]["DIR@FAR=1%"] * 100 for a in AREAS], ":", color=col,
               marker=mk, lw=2, label=f"{meth} DIR @ FAR 1 %")
for a in ax:
    a.invert_xaxis(); a.grid(alpha=.3); a.set_xlabel("Query print area retained (%)")
ax[0].set_ylabel("Rank-1 (%)"); ax[0].set_title("Closed set, 900-print gallery")
ax[1].set_ylabel("DIR (%)"); ax[1].set_title("Open set (450 enrolled / 450 unknown), centred windows")
ax[0].legend(fontsize=7.5, frameon=False); ax[1].legend(fontsize=7.5, frameon=False)
fig.tight_layout()
fig.savefig(f"{R}/headline.png", dpi=130)

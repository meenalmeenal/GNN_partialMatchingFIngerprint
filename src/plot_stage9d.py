"""Tables and figure for Stage 9d (LEADER minutiae extractor): FVC held-out fingers 51-100 and the
900-finger SOCOFing sweep, before vs after the extractor change."""
import json
import os

import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt
import numpy as np

R = "results/stage9d"
AREAS = ["100", "75", "50", "25", "10"]
REAL = [f"fvc{y}_db{d}" for y in (2002, 2004) for d in (1, 2, 3)]
ALL = [f"fvc{y}_db{d}" for y in (2002, 2004) for d in (1, 2, 3, 4)]


def mean(src, key, metric="rank1", dbs=REAL):
    return [100 * np.mean([json.load(open(f"{src}/{db}.json"))["levels"][a][key][metric] for db in dbs])
            for a in AREAS]


ROWS = [  # label, folder, key, colour, style
    ("Classical, default tolerances - old extractor", "results/stage8/heldout", "classical", "#8a8f99", "--"),
    ("Classical, tuned on set B - old extractor", "results/stage9c/fvc_tuned", "classical_tuned", "#b0b4bb", ":"),
    ("Learned, fine-tuned on FVC - old extractor", "results/stage8/heldout", "inv_local_fvcft", "#7fb7c4", "--"),
    ("Classical, default tolerances - LEADER", f"{R}/fvc_oldmodel", "classical", "#79b894", "-"),
    ("Classical, tuned on set B - LEADER", f"{R}/fvc_tuned", "classical_tuned", "#2f7d5d", "-"),
    ("Learned, SOCOFing-trained (old model) on LEADER graphs", f"{R}/fvc_oldmodel", "inv_local_oldmodel", "#c9a35b", "-"),
    ("Learned, retrained on LEADER graphs (SOCOFing only)", f"{R}/fvc_newmodel", "inv_local_leader", "#00798c", "-"),
    ("Learned, retrained + fine-tuned on FVC", f"{R}/fvc_ft", "inv_local_leader_fvcft", "#003f5c", "-"),
]
rows = [(l, f, k, c, s) for l, f, k, c, s in ROWS if all(os.path.exists(f"{f}/{db}.json") for db in REAL)]

out = ["# auto-generated by src/plot_stage9d.py\n",
       "**FVC held-out fingers 51-100, mean over the 6 real-sensor databases, Rank-1 % (chance 2 %)**", "",
       "| method | " + " | ".join(f"{a} %" for a in AREAS) + " |", "|---|" + "---|" * len(AREAS)]
for l, f, k, _, _ in rows:
    out.append(f"| {l} | " + " | ".join(f"{v:.1f}" for v in mean(f, k)) + " |")
out += ["", "**Same, verification EER % (impostor-cohort normalised, lower is better)**", "",
        "| method | " + " | ".join(f"{a} %" for a in AREAS) + " |", "|---|" + "---|" * len(AREAS)]
for l, f, k, _, _ in rows:
    out.append(f"| {l} | " + " | ".join(f"{v:.1f}" for v in mean(f, k, 'eer_z')) + " |")
# per database, 100 % area, the two headline learned models vs tuned classical
out += ["", "**Rank-1 % per database at 100 % area**", "",
        "| database | " + " | ".join(l.split(" - ")[0][:34] + (" (LEADER)" if "LEADER" in l else "") for l, *_ in rows[3:]) + " |",
        "|---|" + "---|" * len(rows[3:])]
for db in ALL:
    cells = []
    for l, f, k, _, _ in rows[3:]:
        p = f"{f}/{db}.json"
        cells.append(f"{json.load(open(p))['levels']['100'][k]['rank1'] * 100:.1f}" if os.path.exists(p) else "-")
    out.append(f"| {db} | " + " | ".join(cells) + " |")

# ---------------------------------------------------------------- LEADER saw some FVC databases in training
UNSEEN = ["fvc2002_db1", "fvc2004_db2", "fvc2002_db4", "fvc2004_db4"]   # not in LEADER's training data
SEEN = ["fvc2002_db3", "fvc2004_db1", "fvc2004_db3"]                     # LEADER trained on their set A (paper)
out += ["", "**LEADER's published training data includes FVC2002 DB3-A, FVC2004 DB1-A and DB3-A (and 100 images of "
        "FVC2002 DB2-A, ambiguous so left out). Rank-1 % at 100 / 50 / 25 / 10 % area split by that:**", "",
        "| method | unseen by LEADER (2002 DB1, 2004 DB2, both synthetic DB4s) | trained-on by LEADER (2002 DB3, 2004 DB1, 2004 DB3) |",
        "|---|---|---|"]
for l, f, k, _, _ in rows:
    cells = []
    for grp in (UNSEEN, SEEN):
        cells.append(" / ".join(f"{100 * np.mean([json.load(open(f'{f}/{db}.json'))['levels'][a][k]['rank1'] for db in grp]):.1f}"
                                for a in ("100", "50", "25", "10")))
    out.append(f"| {l} | " + " | ".join(cells) + " |")

# ---------------------------------------------------------------- SOCOFing 900-finger sweep
new = f"{R}/sweep_centred_leader.json"
if os.path.exists(new):
    nj = json.load(open(new))["modes"]["centred"]
    oj = json.load(open("results/stage9c/sweep_centred.json"))["modes"]["centred"]
    out += ["", "**SOCOFing closed-set Rank-1 %, full test gallery, minutia-centred windows, one random altered probe per finger "
            "(95 % bootstrap CI). Old = Stage 1.5 extractor (900 fingers), new = LEADER (897 fingers: 3 had no usable gallery print)**", "",
            "| extractor | method | " + " | ".join(f"{a} %" for a in AREAS) + " |", "|---|---|" + "---|" * len(AREAS)]
    for name, j in (("old", oj), ("LEADER", nj)):
        for meth in ("learned", "classical"):
            cells = []
            for a in AREAS:
                e = j[a][meth]
                cells.append(f"{e['rank1'] * 100:.1f} [{e['rank1_ci'][0] * 100:.0f}-{e['rank1_ci'][1] * 100:.0f}]")
            out.append(f"| {name} | {meth} | " + " | ".join(cells) + " |")
    out += ["", "**Open-set (z-scored top score), DIR % at FAR 10 % / 1 %, LEADER vs old, learned and classical**", "",
            "| extractor | method | " + " | ".join(f"{a} %" for a in AREAS) + " |", "|---|---|" + "---|" * len(AREAS)]
    for name, j in (("old", oj), ("LEADER", nj)):
        for meth in ("learned", "classical"):
            out.append(f"| {name} | {meth} | " + " | ".join(
                f"{j[a]['open_set'][meth]['z']['DIR@FAR=10%'] * 100:.0f} / {j[a]['open_set'][meth]['z']['DIR@FAR=1%'] * 100:.0f}"
                for a in AREAS) + " |")
open(f"{R}/summary_tables.md", "w", encoding="utf-8").write("\n".join(out))
print("\n".join(out))

fig, ax = plt.subplots(1, 2, figsize=(12.5, 4.8))
x = [int(a) for a in AREAS]
for l, f, k, c, s in rows:
    ax[0].plot(x, mean(f, k), s, color=c, marker="o", ms=4, lw=2, label=l)
    ax[1].plot(x, mean(f, k, "eer_z"), s, color=c, marker="o", ms=4, lw=2)
for a in ax:
    a.invert_xaxis(); a.grid(alpha=.3); a.set_xlabel("Query print area retained (%)")
ax[0].set_ylabel("Rank-1 (%)"); ax[0].set_title("Real FVC prints, held-out fingers (chance 2 %)")
ax[1].set_ylabel("EER (%), lower is better"); ax[1].set_title("Verification")
fig.legend(loc="lower center", ncol=2, fontsize=8, frameon=False)
fig.tight_layout(rect=(0, 0.2, 1, 1))
fig.savefig(f"{R}/headline.png", dpi=130)
